    CODE_EXECUTION = "CODE_EXECUTION"
    IDENTITY_PRIVILEGE = "IDENTITY_PRIVILEGE"
    FINANCIAL = "FINANCIAL"
    INFRASTRUCTURE = "INFRASTRUCTURE"


